using System.Collections.Immutable;
using AwesomeAssertions;
using Kora.Architecture;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Kora.Architecture.Tests;

public sealed class PortableBoundaryAnalyzerTests
{
    private static readonly ImmutableArray<MetadataReference> References =
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
        .Split(Path.PathSeparator)
        .Select(static path => MetadataReference.CreateFromFile(path))
        .ToImmutableArray<MetadataReference>();

    [Theory]
    [InlineData("public interface IWindowsSession { bool IsLocked { get; } }")]
    [InlineData("[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Sequential)] public struct WindowsFrame { public int Value; }")]
    [InlineData("public class C { public bool Check() => System.OperatingSystem.IsWindows(); }")]
    [InlineData("public class C { public void Check() { try { throw new System.InvalidOperationException(); } catch (System.ComponentModel.Win32Exception) { } } }")]
    [InlineData("public class C { public string Name => \"Microsoft.Win32.Registry / DllImport / Windows\"; }")]
    public async Task PortableContractsAndLayoutDoNotAcquirePlatformMechanisms(string source)
    {
        (await AnalyzeAsync(source)).Should().BeEmpty();
    }

    [Theory]
    [InlineData("public class C { public object? Read() => Microsoft.Win32.Registry.GetValue(\"key\", \"value\", null); }")]
    [InlineData("using R = Microsoft.Win32.Registry; public class C { public object? Read() => R.GetValue(\"key\", \"value\", null); }")]
    [InlineData("using static System.Console; public class C { public void Run() => Beep(800, 100); }")]
    [InlineData("public class C { public void Run() { if (System.OperatingSystem.IsWindows()) System.Console.Beep(800, 100); } }")]
    [InlineData("[System.Runtime.Versioning.SupportedOSPlatform(\"windows\")] public class C { }")]
    [InlineData("public class C { [System.Runtime.InteropServices.DllImport(\"kernel32\")] public static extern uint GetCurrentProcessId(); }")]
    [InlineData("using Native = System.Runtime.InteropServices.DllImportAttribute; public class C { [Native(\"kernel32\")] public static extern uint GetCurrentProcessId(); }")]
    [InlineData("public class C { [System.Runtime.InteropServices.LibraryImport(\"kernel32\")] public static uint GetCurrentProcessId() => 0; }")]
    [InlineData("[System.Runtime.InteropServices.ComImport, System.Runtime.InteropServices.Guid(\"00000000-0000-0000-0000-000000000001\")] public interface ICom { }")]
    [InlineData("public class C { public nint Load() => System.Runtime.InteropServices.NativeLibrary.Load(\"native\"); }")]
    [InlineData("public class C { public int Error => System.Runtime.InteropServices.Marshal.GetLastPInvokeError(); }")]
    [InlineData("public class C { public Microsoft.Win32.SafeHandles.SafeFileHandle? Handle { get; } }")]
    [InlineData("public class C { public System.Type NativeType => typeof(System.Runtime.InteropServices.NativeMemory); }")]
    [InlineData("public class C { public System.Exception Error() => new System.ComponentModel.Win32Exception(); }")]
    [InlineData("#pragma warning disable KORAARCH002\npublic class C { public void Run() => System.Console.Beep(800, 100); }")]
    public async Task PlatformApiFailsEvenWithAliasesGuardsOrSuppression(string source)
    {
        (await AnalyzeAsync(source)).Should().NotBeEmpty()
            .And.OnlyContain(static diagnostic => diagnostic.Id == PortableBoundaryAnalyzer.DiagnosticId
                && diagnostic.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public async Task GeneratedSourceIsAlsoChecked()
    {
        (await AnalyzeAsync("// <auto-generated/>\npublic class C { public void Run() => System.Console.Beep(800, 100); }", "Fixture.g.cs"))
            .Should().NotBeEmpty();
    }

    private static async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(string source, string path = "Fixture.cs")
    {
        var compilation = CSharpCompilation.Create(
            "Fixture",
            [CSharpSyntaxTree.ParseText(source, path: path)],
            References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        compilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .Should().BeEmpty("the fixture must be valid C#, not fail because of a missing API/reference");
        return await compilation.WithAnalyzers([new PortableBoundaryAnalyzer()]).GetAnalyzerDiagnosticsAsync();
    }
}
